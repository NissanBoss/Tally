// Three archives written by 7-Zip itself, kept as bytes.
//
// A 7z cannot be built here the way a zip can, because building one means
// writing an LZMA compressor and this program only has a decoder. So these
// are the real thing, made by 7-Zip on Windows from the same three files,
// and the point of having two of them is the check in the middle: one has
// its listing compressed and one does not, and the two have to come out
// saying exactly the same thing. If the decoder is wrong anywhere, they
// will not.
//
//	plain   the default, so the listing is an LZMA stream
//	nohdr   made with -mhc=off, so the listing is in the clear
//	locked  made with -mhe=on, so the listing is encrypted

import "encoding/hex"

func unhex(s string) []byte {
	out, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return out
}

